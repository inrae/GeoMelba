class Pdf_generator:

    """
    Generation Schema
    Attribute Table ---> CSV ---> JSON ---> processing ---> Jinja2 ---> HTML ---> PDF

    This class manages the entire PDF generation process when displaying results. The code is modular but cannot implement certain specific and atypical technical features of a watershed.
    """
    
    def __init__(self,output_path=None,watershed_name=None,count_turn=None,season=None,studied_elements=None):
        """
        init global variable and usefull path
        """
        self.racine = path
        
        self.output_path = output_path
        self.watershed_name = watershed_name
        self.count_turn = count_turn
        self.season = season
        self.studied_elements = studied_elements

        self.actual_path = os.path.dirname(__file__) + "/"
        self.json_path = os.path.join(self.actual_path + "json/") #json directory
        self.templates_path = os.path.join(self.actual_path + "templates") #jinja2 template directory
        self.gpkg_path = os.path.join(self.output_path + "/" + data_output_folder + "/" + data_layer + watershed_name + ".gpkg") #gpkg file changer ici le nom du fichier
        self.previous_path = os.path.join(self.json_path, 'previous_stade.json')
        # 0 if it's save data turn, 1 if not
        self.global_state = 1

        self.list_layer = [line_layer_name,parcel_layer_name] #if a new layer is added to the gpkg file, it is important to add it here
        
        self.previous_stade_json_path = os.path.join(self.json_path + "previous_stade.json")

    def start_extraction(self):
        """Make the calculation and extract"""
        
        self.table_to_csv() # This function transforms the attribute table in the .gpkg file into a csv

        # Dictionary to store all the data from the different layers
        donnees = {}
        
        # It traverses the layers to find the associated CSV files and thus creates a JSON. Then, it loads the JSON file into donnees.
        for elt in self.list_layer :
            self.csv_to_json(self.actual_path + elt + '_data.csv', self.json_path + elt + '.json')
            with open(self.json_path + elt + '.json', "r") as fichier_json:
                donnees[elt] = json.load(fichier_json)
            
        # Load jinja2 template environment
        env = Environment(loader=FileSystemLoader(self.templates_path))
        template = env.get_template('template.html.jinja2')
                
        # We send all the data from the desired layer to its specific processing function
        exutoire_out = self.exutoire_call()
        surface_out = self.parcellaire_by_type(donnees[parcel_layer_name])
        practices_out = self.practices_by_type(donnees[parcel_layer_name])
        lineaire_out = self.lineaire_by_type(donnees[line_layer_name])
        creation_date=datetime.datetime.today().strftime('%Y-%m-%d %H:%M:%S')
        
        # jinja2 template render html with parameter

        html = template.render(output=self.output_path,count=self.count_turn, watershed_name=self.watershed_name,season=self.season,
                               studied_elements=self.studied_elements[0],exutoire=exutoire_out[2], evolution_exutoire=exutoire_out[1],
                               dict_surface=surface_out[0], keys_surface=surface_out[1],percent_surface=surface_out[2], ev_surface=surface_out[3],
                               dict_lineaire=lineaire_out[0], keys_lineaire=lineaire_out[1], ev_lineaire=lineaire_out[2],
                               dict_practices=practices_out[0],keys_practices=practices_out[1], percent_practices=practices_out[2], ev_practices=practices_out[3],
                               creation_date=creation_date)
        
        previous_stade_json_path = os.path.join(self.json_path, "previous_stade.json")

        if self.global_state == 0:

            # create backup of the current turn, we can just use a dictionnary but list able a bigger modularity
            previous = [{
                "turn": self.count_turn,
                "watershed": self.watershed_name,
                "season": self.season,
                "studied_elements": self.studied_elements,
                "surface_out": surface_out,
                "practices_out": practices_out,
                "lineaire_out": lineaire_out
            }]

            with open(previous_stade_json_path, "w") as json_file:
                json.dump(previous, json_file)
        
        self.global_state = 1
        
        return html
    
    def start_pdf_generation(self,html):
        # Path definition
        filename = 'id_BV_'+str(self.count_turn)+'.pdf'
        input_html = os.path.join(self.actual_path, 'index.html')
        output_pdf = os.path.join(self.output_path, filename)
        css = os.path.join(self.actual_path, 'style.css')

        # write html with render
        with open(input_html, "w") as fichier_html:
            fichier_html.write(html)

        # convert html to pdf
        try :
            HTML(filename=input_html).write_pdf(output_pdf,stylesheets=[css])
        except Exception as e :
                print("import exceptions for lib weasyprint and dependency. HTML file was created but not the pdf. You can find it here:")
                print(input_html)
                print(e)
                #if pdf can't be generated html file are make in output folder
                output_html = os.path.join(self.output_path, 'index.html')
                shutil.copy(os.path.join(self.actual_path, 'style.css'),os.path.join(self.output_path, 'style.css'))
                with open(output_html, "w") as fichier_html:
                    fichier_html.write(html)

    def table_to_csv(self):
        """
        From single attribute table to different csv
        """
        layer_path = self.gpkg_path

        # loop to take only wanted layer
        for elt in self.list_layer :
            layer = QgsVectorLayer(layer_path + "|layername=" + elt, elt, "ogr")

            # check if the layer exist in attribute table
            if not layer.isValid():
                print("The layer is not valid. Please check the GeoPackage file path and the layer name.")
            else:
                chemin_csv = os.path.join(self.actual_path + elt +"_data.csv")

                #create a csv with ; as separator
                with open(chemin_csv, "w") as fichier_csv:
                    header = [field.name() for field in layer.fields()]
                    fichier_csv.write(";".join(header) + "\n") 

                    for feature in layer.getFeatures():
                        valeurs = [str(feature[field.name()]) for field in layer.fields()]
                        fichier_csv.write(";".join(valeurs) + "\n")
            
    def csv_to_json(self,csv_file, json_file):
        """
        JSON files are easier and faster to manipulate. That's why we create JSON files from csv.
        """
        data = []
        with open(csv_file, 'r') as csvfile:
            csvreader = csv.DictReader(csvfile, delimiter=';')
            for row in csvreader:
                data.append(row)
        with open(json_file, 'w') as jsonfile:
            json.dump(data, jsonfile, indent=4)

    def get_all_key_from_dict(self,dict):
        """
        get the key of a dictionnary
        """
        key_list = list(dict.keys())
        return key_list

    def get_percent(self,data):
        """
        Calculate the percentage of each element with the same key relative to the others.
        """
        total = sum(data.values())
        percent_dict = {key: round((value / total) * 100, 2) for key, value in data.items()}
        return percent_dict

    def parcellaire_by_type(self,data):
        """
        Processes surface data by soil types.
        Input:
            - data: dictionary containing information from the layer necessary for calculations
        Output:
            - surfaces_totals: dictionary with the surface area in hectares for each type of plot
            - keys: list of dictionary keys, allowing for field merging, key mapping to their names, and simplifying traversal
            - percent: percentage of each type
            - evolution: evolution indicator
        """
        

        # Mapping to get real name instead of int value for keys
        mapping = {}
        config_land_cover_file_csv = os.path.splitext(config_land_cover_file_json)[0] + '.csv'
        UH_land_cover_csv_file_path = self.output_path + "/" + data_output_folder + "/" + config_land_cover_file_csv

        with open(UH_land_cover_csv_file_path,  newline='') as csvfile:
            reader = csv.DictReader(csvfile)
            for row in reader:
                mapping[int(row['value'])] = row['key']

        # performs area, conversion and rounding calculations
        def calculate_surface_totals(data):
            surface_totals = defaultdict(int)
            for entry in data:
                surface_totals[mapping[int(entry[field_type_parcel])]] += round(float(entry[field_parcel_area]) / 10000, 2)
            return surface_totals

        # getting value from function
        surfaces_totals = calculate_surface_totals(data)
        keys = self.get_all_key_from_dict(surfaces_totals)
        percent = self.get_percent(surfaces_totals)
        
        # mapping of key to get name instead of int
        keys = list(mapping.values())
        
        #calculate evolution, be careful to put after mapping 
        evolution = self.evolution(surfaces_totals,keys,"surface_out")
        
        return surfaces_totals, keys, percent, evolution

    def practices_by_type(self,data):
        """
        Processes practices data by soil types.
        Input:
            - data: dictionary containing information from the layer necessary for calculations
        Output:
            - practices_totals: dictionary with the surface area in hectares for each type of plot
            - keys: list of dictionary keys, allowing for field merging, key mapping to their names, and simplifying traversal
            - percent: percentage of each type
            - evolution: evolution indicator
        """
        

        
        # Mapping to get real name instead of int value for keys
        mapping = {}

        agricultural_practices_type_file_csv = os.path.splitext(config_practices_file_json)[0] + '.csv'
        agricultural_practices_csv_file_path = self.output_path + "/" + data_output_folder + "/" + agricultural_practices_type_file_csv

        with open(agricultural_practices_csv_file_path, newline='') as csvfile:

            reader = csv.DictReader(csvfile)
            for row in reader:
                mapping[int(row['value'])] = row['key']

        #if watershed have zero practices:

        if len(mapping) == 1 and mapping[1]=="none" :
            return None, None, None, None
              
        # performs area, conversion and rounding calculations
        def calculate_practices_totals(data):
            practices_totals = defaultdict(int)
            for entry in data:
                if entry[field_parcel_practice] == "99" :
                    pass #for N/A data
                else :
                    practices_totals[mapping[int(entry[field_parcel_practice])]] += round((float(entry[field_parcel_area])/10000),2)
            return practices_totals
            
        practices_totals = calculate_practices_totals(data)
        keys=self.get_all_key_from_dict(practices_totals)
        percent = self.get_percent(practices_totals)
        
        # mapping of key to get name instead of int
        keys = list(mapping.values())
        
        #calculate evolution, be careful to put after mapping 
        ev = self.evolution(practices_totals,keys,"practices_out")

        return practices_totals, keys, percent, ev

    def lineaire_by_type(self,data):
        """
        Processes surface data by lineaire types.
        Input:
            - data: dictionary containing information from the layer necessary for calculations
        Output:
            - surfaces_totals: dictionary with the surface area in meter for each type of plot
            - keys: list of dictionary keys, allowing for field merging, key mapping to their names, and simplifying traversal
            - evolution: evolution indicator
        """
        
        # performs lineaire, conversion and rounding calculations
        def calculate_lineaire_totals(data):
            lineaire_totals = defaultdict(int)
            for entry in data:
                lineaire_totals[mapping[int(entry[field_type_line_middle])]] += float(entry[field_line_length])
                lineaire_totals[mapping[int(entry[field_type_line_top])]] += float(entry[field_line_length])
                lineaire_totals[mapping[int(entry[field_type_line_bottom])]] += float(entry[field_line_length])
                
            return lineaire_totals

        # mapping to get real name instead of int value for keys
        mapping = {}
        config_line_type_file_csv = os.path.splitext(config_line_type_file_json)[0] + '.csv'
        line_type_csv_file_path = self.output_path + "/" + data_output_folder + "/" + config_line_type_file_csv

        with open(line_type_csv_file_path, newline='') as csvfile:

            reader = csv.DictReader(csvfile)
            for row in reader:
                mapping[int(row['value'])] = row['key']

        
        lineaire_totals = calculate_lineaire_totals(data)
        keys=self.get_all_key_from_dict(lineaire_totals)
        
        keys = list(mapping.values())
        
        ev = self.evolution(lineaire_totals,keys,"lineaire_out")

        return lineaire_totals, keys, ev

    def exutoire_call(self):
        """
        To calculate the outlet value in % based on the initial situation (at 100%)
        """
        
        #path definition
        exutoire_csv_path = os.path.join(self.output_path, data_output_folder, "exutoire_value.csv")
        exutoire_json_path = os.path.join(self.output_path, data_output_folder, "exutoire_value.json")
        self.csv_to_json(exutoire_csv_path,exutoire_json_path)

        with open(exutoire_json_path, "r") as fichier_json:
            donnees = json.load(fichier_json)
            
        
        #return ex value and 0 if it's better and 1 if it's badless and 2 if it's equal and 3 if there is no past data
        def get_lastex_value(donnees):
            
            try :
                with open(self.previous_stade_json_path, "r") as fichier_json:
                    initial = json.load(fichier_json) # contains all previous state
                    initial = initial[0]["turn"]
            except FileNotFoundError as e:
                initial = self.count_turn
            
            if len(donnees) > 1:
                # to compare with last turn
                # temp = donnees[-1:]
                # val_old = float(temp[0]['value'])
                # val_new = float(temp[1]['value'])
                # to compare with initial turn
                val_old = float(donnees[initial]['value'])
                first_value = float(donnees[initial]['value'])
                val_new = float(donnees[self.count_turn]['value']) #prend la valeur du tour actuel
                if val_old > val_new:
                    ev = 0
                elif val_new > val_old:
                    ev = 1
                else:
                    ev = 2
                evolution_percentage = round((((val_new - first_value) / first_value) * 100),0)
            else:
                val_new = float(donnees[initial]['value'])
                ev = 3
                evolution_percentage = 0

            evolution_percentage = int((100+evolution_percentage))
            return val_new, ev, evolution_percentage
        
        #create a graphe with plt lib
        def graphe_creation(donnees):
            valeurs = [float(d['value']) for d in donnees]
            
            ratio = 100 / valeurs[0]
            
            valeurs = [v * ratio for v in valeurs]
            
            pas = range(0, len(donnees))

            plt.plot(pas, valeurs)
            plt.xlabel('Tour')
            plt.ylabel('Valeur en % ')
            plt.title('Évolution de la valeur à l\'exutoire en % par tour')
            plt.xticks(rotation=45) 
            plt.grid(True)
            plt.savefig(os.path.join(self.output_path, "ex_evolution"))  # correction de l'erreur de path
            plt.close()
        
        report = get_lastex_value(donnees)
        try :
            graphe_creation(donnees)
        except Exception as e :
            print("import exceptions for lib matplotlib and dependency")
            print(e)
            
        return report  

    def evolution(self,data,keys,type):
        """
        Allows you to determine how data evolves

        Input :
            - data default dict of other function
            - list of keys
            - type (parcellaire, lineaire, practices)
        
        Output :
            Dictionnary with 0 if it's higher and 1 if it's lower and 2 if it's equal and 3 if there is no past data for each element.
        """
        
        try :
            with open(self.previous_stade_json_path, "r") as fichier_json:
                previous = json.load(fichier_json) # contains all previous state
        except FileNotFoundError :
            previous = None
        
        #with my implementation the function research -1 turn, he doesn't existe. This line prevent this case
        if self.count_turn == 0 :
            previous = None
            
        if previous :
            #find dictionnary of the previous turn, 'turn' contains primary key previous contain only one line
            # previous = [item for item in previous if item['turn'] == 0]
            previous = [item for item in previous]
            previous = previous[0]

        evolution = {}

        # return ex value
        # 0 if it's better
        # 1 if it's badless
        # 2 if it's equal
        # 3 if there is no past data
        if previous is not None :
            previous_type = previous[type][0]
            for key in keys:
                val_old = previous_type[key]
                val_new = data[key]
                if val_old > val_new:
                    evolution[key] = 0
                elif val_new > val_old:
                    evolution[key] = 1
                else:
                    evolution[key] = 2
        else :
            for key in keys:
                evolution[key] = 3

        return evolution

